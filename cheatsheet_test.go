// renderCheatSheet is the sheet's markdown from the runtime's default rows.
func renderCheatSheet(doc ochazuke.BindingsDoc) (string, error) {
	var b strings.Builder
	b.WriteString("The keys below are o-json's defaults; your own `bindings.json` may change them, and `?` always shows the keys as they are.\n")
	for _, s := range cheatSheet {
		fmt.Fprintf(&b, "\n**%s**\n\n| Keys | Does |\n|---|---|\n", s.title)
		for _, l := range s.lines {
			keys, err := sheetKeys(doc, l)
			if err != nil {
				return "", err
			}
			fmt.Fprintf(&b, "| %s | %s |\n", keys, l.does)
		}
	}
	return b.String(), nil
}

// sheetKeys lists, in row order, every key a row binds to the line's
// action and args in its context.
func sheetKeys(doc ochazuke.BindingsDoc, l sheetLine) (string, error) {
	want, _ := json.Marshal(l.args)
	var keys []string
	seen := map[string]bool{}
	for _, g := range doc.Groups {
		if g.Instance != "" || !sameAction(g.Context(), l.context) {
			continue
		}
		for _, row := range g.Rows {
			if row.Unbind || row.Keys == "" || !sameAction(row.Request.Noun+"."+row.Request.Verb, l.action) {
				continue
			}
			var args map[string]any
			if len(row.Request.Args) > 0 {
				args = row.Request.Args
			}
			if got, _ := json.Marshal(args); !bytes.Equal(got, want) {
				continue
			}
			if !seen[row.Keys] {
				seen[row.Keys] = true
				keys = append(keys, "`"+strings.ReplaceAll(row.Keys, "|", `\|`)+"`")
			}
		}
	}
	if len(keys) == 0 {
		var there []string
		for _, g := range doc.Groups {
			if g.Instance == "" && sameAction(g.Context(), l.context) {
				for _, row := range g.Rows {
					there = append(there, row.Keys+"="+row.Request.Noun+"."+row.Request.Verb)
				}
			}
		}
		return "", fmt.Errorf("cheat sheet: no row in %s binds %s %s (it binds %s)", l.context, l.action, want, strings.Join(there, " "))
	}
	return strings.Join(keys, " "), nil
}

// sameAction reports whether name, as the runtime holds it, is the
// bindings.json spelling short: a framework noun ("detail",
// "outline.fold") is stored under ochazuke's prefix.
func sameAction(name, short string) bool {
	return name == short || name == "ochazuke."+short
}

// TestCheatSheet fails when the cheat sheet committed in docs/GUIDE.md is
// not what the key rows generate (regenerate: scripts/cheatsheet.sh).
func TestCheatSheet(t *testing.T) {
	t.Setenv("XDG_CONFIG_HOME", t.TempDir())
	t.Setenv("XDG_STATE_HOME", t.TempDir())
	a := open(t, "testdata/sample.json", 120, 40)
	sheet, err := renderCheatSheet(a.r.DefaultBindingsDoc())
	if err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(guidePath)
	if err != nil {
		t.Fatal(err)
	}
	guide := string(data)
	start, end := strings.Index(guide, cheatSheetOpen), strings.Index(guide, cheatSheetEnd)
	if start < 0 || end < start {
		t.Fatalf("%s has no %q ... %q block", guidePath, cheatSheetOpen, cheatSheetEnd)
	}
	body := start + len(cheatSheetOpen)
	want := "\n" + sheet
	if guide[body:end] == want {
		return
	}
	if os.Getenv("UPDATE_CHEATSHEET") != "" {
		if err := os.WriteFile(guidePath, []byte(guide[:body]+want+guide[end:]), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("rewrote the cheat sheet in %s", guidePath)
		return
	}
	t.Fatalf("the cheat sheet in %s no longer matches the key rows; regenerate with scripts/cheatsheet.sh (UPDATE_CHEATSHEET=1 go test -run '^TestCheatSheet$' .) and commit it\n--- generated ---\n%s", guidePath, sheet)
}
