// The cheat sheet at the end of docs/GUIDE.md is generated from the key
// rows: o-json's bindings.json and the ochazuke rows it runs with (tab, ?,
// :, the outline's h/l), as the runtime holds them before any user file.
// Each line below names a context and an action (with its args); the keys
// are whatever rows bind it there, so a changed key changes the sheet and
// TestCheatSheet fails until it is regenerated:
//
//	UPDATE_CHEATSHEET=1 go test -run '^TestCheatSheet$' .   (scripts/cheatsheet.sh)
//
// A line whose action no row binds is an error, so a removed binding
// cannot leave a stale line behind.

